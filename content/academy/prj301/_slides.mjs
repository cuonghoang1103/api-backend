const bookName = (k, lang) => {
  const b = BOOKS[k];
  if (!b) throw new Error(`unknown book ${k}`);
  return typeof b === 'string' ? b : b[lang];
};

/** "Read in the books" block: refs = [[bookKey, whereEn, whereVi], …]. */
export function books(refs) {
  const li = (lang) => refs.map(([k, en, vi]) => `<li>${bookName(k, lang)}: <strong>${lang === 'en' ? en : vi}</strong></li>`).join('');
  return `<div class="ml-en"><h3>📚 Read it in the book</h3><ul>${li('en')}</ul></div>\n` +
    `<div class="ml-vi"><h3>📚 Đọc thêm trong sách (đúng chương, đúng trang)</h3><ul>${li('vi')}</ul></div>`;
}

/** Wrap paired blocks: bi(en, vi). */
