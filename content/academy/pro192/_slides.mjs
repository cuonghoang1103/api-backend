/**
 * Add a deck from another module without editing this shared file.
 * Call at import time, before using slide()/walk().
 */
export function registerDeck(key, meta) {
  if (DECKS[key] && JSON.stringify(DECKS[key]) !== JSON.stringify(meta)) throw new Error(`deck ${key} already registered differently`);
  DECKS[key] = meta;
}

const pad = (n) => String(n).padStart(3, '0');
const attr = (s) => String(s).replace(/<[^>]+>/g, '').replace(/&/g, '&amp;').replace(/"/g, '&quot;');

/** Public URL of one rendered slide. */
export const img = (deck, n) => `${CDN_ROOT}/${DECKS[deck]?.ver || 'v1'}/${deck}/${pad(n)}.webp`;

/**
 * One slide = the picture (shared by both languages, so it is fetched once)
 * followed by the paired EN/VI explanation. `title` is plain slide text.
 */
export function slide(deck, n, title, en, vi) {
  const d = DECKS[deck];
  if (!d) throw new Error(`unknown deck ${deck}`);
  if (n < 1 || n > d.total) throw new Error(`${deck} has ${d.total} slides, got ${n}`);
  return `<div class="anh-slide"><img src="${img(deck, n)}" alt="${attr(`${d.code} slide ${n}: ${title}`)}" loading="lazy" width="${d.w}" height="${d.h}" />` +
    `<p class="chu-thich">📑 <strong>${d.code}</strong> · slide ${n}/${d.total} — ${title}</p></div>\n` +
    `<div class="ml-en giang">${en}</div>\n<div class="ml-vi giang">${vi}</div>`;
}

/** A run of slides: rows = [[n, title, en, vi], …]. */
export const walk = (deck, rows) => rows.map((r) => slide(deck, ...r)).join('\n');

/** Answer line for an in-class "Question" slide. */
export const ansEn = (letter, why) => `<p class="dap-an">✅ <strong>Answer: ${letter}.</strong> ${why}</p>`;
export const ansVi = (letter, why) => `<p class="dap-an">✅ <strong>Đáp án: ${letter}.</strong> ${why}</p>`;

/** Heading that opens a slide walkthrough. */
export function walkHead(deck, from, to, noteEn = '', noteVi = '') {
  const d = DECKS[deck];
  return `<div class="ml-en"><h2>📑 Slide by slide — ${d.code} (${d.en}), slides ${from}–${to}</h2>` +
    `<p>Open your own copy of the deck <em>${d.code}</em> next to this page. Each slide is shown exactly as in class, followed by its key idea, a plain explanation with the English terms explained, a real diagram (PlantUML, rendered for real — open the source under the picture and edit it), and — whenever the slide shows code or a command — a real Java program that was compiled and run, with the output it really printed (code meant for the exam room is checked on a real JDK 8 too), a memory tip and the exam trap. ${noteEn}</p></div>\n` +
    `<div class="ml-vi"><h2>📑 Học theo từng slide — ${d.code} (${d.vi}), slide ${from}–${to}</h2>` +
    `<p>Mở bộ slide <em>${d.code}</em> của thầy/cô bên cạnh trang này. Mỗi slide được giữ nguyên như trên lớp, ngay dưới là ý chính, giải thích dễ hiểu kèm nghĩa tiếng Việt của thuật ngữ, sơ đồ thật (PlantUML dựng thật — mở mã ngay dưới hình để tự sửa), và — khi slide có code hay lệnh — một chương trình Java đã biên dịch và chạy thật cùng output nó thật sự in ra (code dùng ở phòng thi được kiểm thêm trên JDK 8 thật), mẹo nhớ và bẫy hay mất điểm. ${noteVi}</p></div>`;
}

