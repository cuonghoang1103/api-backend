// ── 5. source rules (comments and string contents are ignored) ──
function strip(src) {
  let o = '', i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') { while (i < n && src[i] !== '\n') { o += ' '; i++; } continue; }
    if (c === '/' && d === '*') { o += '  '; i += 2; while (i < n && !(src[i] === '*' && src[i + 1] === '/')) { o += src[i] === '\n' ? '\n' : ' '; i++; } o += '  '; i += 2; continue; }
    if (c === '"' && src.startsWith('"""', i)) { o += '""'; i += 3; while (i < n && !src.startsWith('"""', i)) { o += src[i] === '\n' ? '\n' : ''; i++; } i += 3; continue; }
    if (c === '"' || c === "'") { o += c; i++; while (i < n && src[i] !== c && src[i] !== '\n') { if (src[i] === '\\') i++; i++; } o += c; i++; continue; }
    o += c; i++;
  }
  return o;
}
const files = mine.map((f) => { const raw = fs.readFileSync(f, 'utf8'); return { name: path.relative(path.join(HERE, DE.src), f).split(path.sep).join('/'), raw, code: strip(raw) }; });
const lineOf = (code, idx) => code.slice(0, idx).split('\n').length;
function regexRule(r) {
  const re = new RegExp(r.re, r.flags || 'gm');
  const scope = files.filter((f) => (!r.file || new RegExp(r.file).test(f.name)) && (!r.scanner || /\bScanner\b/.test(f.code)));
  const hits = [];
  for (const f of scope) { const t = r.raw ? f.raw : f.code; for (const m of t.matchAll(re)) hits.push(`${f.name}:${lineOf(t, m.index)}`); }
  if (r.need) return hits.length ? [] : [r.file ? `not found in ${r.file}` : 'not found'];
  return hits;
}
// r.same = { 'Main.java': fingerprint }: a GIVEN file must stay as given (whitespace and line endings do not matter)
const fingerprint = (t) => crypto.createHash('sha1').update(String(t).replace(/\s+/g, '')).digest('hex').slice(0, 12);
function sameRule(r) {
  const hits = [];
  for (const [name, want] of Object.entries(r.same)) {
    const f = files.find((x) => x.name === name);
    if (!f) hits.push(`${name} missing`);
    else if (fingerprint(f.raw) !== want) hits.push(`${name} changed`);
  }
  return hits;
}
