// Captcha runs: the input is typed line by line; at a {CAP…} line the grader waits until the program is idle at a prompt,
// takes the LAST captcha it printed and fills it in.
function runLive(c, input, dir) {
  return new Promise((done) => {
    const p = spawn(java.cmd, javaArgs(c), { cwd: dir });
    let out = '', err = '', last = Date.now(), finished = false, timedOut = false, tooBig = false;
    const caps = () => [...out.matchAll(new RegExp(DE.captcha.show, 'g'))].map((m) => m[1]);
    p.stdout.setEncoding('utf8');
    p.stderr.setEncoding('utf8');
    p.stdout.on('data', (d) => { out += d; last = Date.now(); if (out.length > MAX_OUT) { tooBig = true; p.kill(); } });
    p.stderr.on('data', (d) => { err += d; last = Date.now(); });
    p.stdin.on('error', () => { /* program ended early */ });
    const killer = setTimeout(() => { timedOut = true; p.kill(); }, DE.timeoutMs);
    p.on('close', (code, signal) => { finished = true; clearTimeout(killer); done({ stdout: out, stderr: err, status: code, signal, error: timedOut ? { code: 'ETIMEDOUT' } : tooBig ? { code: 'ENOBUFS' } : null }); });
    const lines = String(input).replace(/\n$/, '').split('\n');
    const prompt = new RegExp(DE.captcha.prompt);
    (async () => {
      for (const line of lines) {
        if (finished) return;
        if (/\{CAP(1|MID)?\}/.test(line)) {
          // wait: idle 200 ms at the captcha prompt (or idle 1.5 s anywhere — your prompt may differ)
          for (;;) {
            await new Promise((r) => setTimeout(r, 25));
            if (finished) return;
            const idle = Date.now() - last;
            const tail = out.slice(out.lastIndexOf('\n') + 1);
            if ((idle >= 200 && prompt.test(tail)) || idle >= 1500) break;
          }
          const all = caps();
          const cap = all.length ? all[all.length - 1] : '';
          p.stdin.write(line.replace('{CAP1}', cap.slice(0, 1)).replace('{CAPMID}', cap.slice(1, 3)).replace('{CAP}', cap) + '\n');
        } else p.stdin.write(line + '\n');
      }
      p.stdin.end();
    })();
  });
}
async function runCase(c) {
  const dir = fs.mkdtempSync(path.join(work, 'case-'));
  for (const [f, text] of Object.entries(c.files || (c.filesRef ? DE.shared[c.filesRef] : {}))) {
    fs.mkdirSync(path.dirname(path.join(dir, f)), { recursive: true });
    fs.writeFileSync(path.join(dir, f), text);
  }
  const sessions = c.sessions || [c.input ?? ''];
  let out = '', err = '', crash = null;
  let caps = [];
  for (const [i, input] of sessions.entries()) {
    if (crash) break;
    if (i > 0) out += `===== RESTART: session ${i + 1} (same folder, files kept) =====\n`;
    const r = DE.captcha ? await runLive(c, input, dir)
      : spawnSync(java.cmd, javaArgs(c), { cwd: dir, input, encoding: 'utf8', timeout: DE.timeoutMs, maxBuffer: MAX_OUT });
    if (capRe) caps = caps.concat([...String(r.stdout || '').matchAll(new RegExp(DE.captcha.show, 'g'))].map((m) => m[1]));
    out += mask(r.stdout || '');
    err += r.stderr || '';
    if (r.error && r.error.code === 'ENOBUFS') crash = `STOPPED: more than ${MAX_OUT >> 20} MB of output — an endless loop, often after the input ran out (a catch (Exception) around nextLine() keeps asking forever at the end of the input) · in quá ${MAX_OUT >> 20} MB — vòng lặp vô tận, thường do hết input mà vẫn hỏi lại`;
    else if (r.error && r.error.code === 'ETIMEDOUT') crash = `TIMEOUT after ${DE.timeoutMs} ms — an endless loop? (e.g. the menu never reads the exit choice) · quá giờ — vòng lặp vô tận?`;
    else if (r.status !== 0 || /Exception in thread|^Exception|Error: /m.test(r.stderr || '')) {
      crash = `CRASHED (exit ${r.status ?? r.signal}) · chương trình SẬP:\n${String(r.stderr || '').split(/\r?\n/).filter(Boolean).slice(0, 6).map((l) => '      ' + l).join('\n')}`;
    }
  }
  // the captcha must be NEW at every login: 3+ captchas in one run that are all equal ⇒ not random
  if (!crash && DE.captcha && caps.length >= 3 && new Set(caps).size === 1) {
    crash = `the captcha "${caps[0]}" is the same at all ${caps.length} logins — generate a new random one each time · captcha phải sinh ngẫu nhiên MỚI mỗi lần đăng nhập`;
  }
  return { out, err, crash };
}

