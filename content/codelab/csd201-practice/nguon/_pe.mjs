/** Tệp THẬT của các đề (given materials, đổi CRLF→LF): pe1_* = SP26 Paper 1, pe3_* = SP26 Block 5 Paper 4. */
export const PE_THAT = (f) => doc(f);

/** Main.java đúng như given materials (lớp t, số câu f1..fN, điểm mỗi câu). */
export function mainPe(lop, soF, diem = 1) {
  const cas = Array.from({ length: soF }, (_, i) => `       case ${i + 1}: t.f${i + 1}();
               System.out.println("Your output:");
               Lib.viewFile("f${i + 1}.txt");
               break;`).join('\n');
  return `// ======= DO NOT EDIT THIS FILE ============
import java.io.*;
import java.util.*;
class Main {
   public static void main(String args[]) throws Exception {
    ${lop} t = new ${lop}();
    int choice;
    Scanner sca = new Scanner(System.in);
    System.out.println();
${Array.from({ length: soF }, (_, i) => `    System.out.println(" ${i + 1}. Test f${i + 1} (${diem} mark)");`).join('\n')}
    System.out.println(" 0. Exit");
    System.out.print("    Your selection (0 -> ${soF}): ");
    choice = sca.nextInt();
    sca.nextLine();
    if(choice==0) return;
    switch(choice) {
${cas}
       default: System.out.println("Wrong selection");
      }
     System.out.println();
   }
 }
`;
}

/** Luật phòng thi: không chữ tiếng Việt có dấu (mọi ký tự ngoài ASCII) trong tệp người học sửa — kể cả trong chú thích. */
const asciiRule = (file) => ({ id: 'P1', en: `${file} is plain ASCII — no Vietnamese accents even in comments ("Khong su dung tieng Viet co dau": the exam machine gives 0)`, vi: `${file} chỉ chứa ASCII — không tiếng Việt có dấu kể cả trong chú thích (đề ghi: dùng là bị lỗi, 0 điểm)`, re: String.raw`[^\x00-\x7F]`, raw: true, file: `^${file.replace('.', '\\.')}$` });

