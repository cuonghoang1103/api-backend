function fieldsPrivate() {
  const hits = [];
  for (const f of files) {
    if (/\binterface\s+\w+/.test(f.code) && !/\bclass\s+\w+/.test(f.code)) continue;
    let depth = 0;
    f.code.split('\n').forEach((line, i) => {
      const s = line.trim();
      if (depth === 1 && /;\s*$/.test(s) && !/[()]/.test(s.split('=')[0]) && !/^(return|throw|package|import)\b/.test(s)
        && /^((public|protected|private|static|final|transient|volatile)\s+)*[\w<>[\],.? ]+\s+\w+\s*(=.*)?;$/.test(s)) {
        const mods = s.match(/^((public|protected|private|static|final|transient|volatile)\s+)*/)[0];
        if (!/\bprivate\b/.test(mods) && !(/\bstatic\b/.test(mods) && /\bfinal\b/.test(mods))) hits.push(`${f.name}:${i + 1}`);
      }
      depth += (line.match(/\{/g) || []).length - (line.match(/\}/g) || []).length;
    });
  }
  return hits;
}
function switchDefault() {
  const hits = [];
  for (const f of files) {
    for (const m of f.code.matchAll(/\bswitch\s*\(/g)) {
      let i = f.code.indexOf('{', m.index), depth = 0, j = i;
      for (; j < f.code.length; j++) { if (f.code[j] === '{') depth++; else if (f.code[j] === '}' && --depth === 0) break; }
      if (!/\bdefault\b/.test(f.code.slice(i, j))) hits.push(`${f.name}:${lineOf(f.code, m.index)}`);
    }
  }
  return hits;
}
function overrides() {
  const hits = [];
  for (const f of files) {
    for (const m of f.code.matchAll(/^[ \t]*public\s+[\w<>[\]]+\s+(toString|equals|hashCode|compareTo|compare)\s*\(/gm)) {
      const before = f.code.slice(0, m.index).replace(/\s+$/, '');
      if (!/@Override$/.test(before)) hits.push(`${f.name}:${lineOf(f.code, m.index)} ${m[1]}()`);
    }
  }
  return hits;
}
