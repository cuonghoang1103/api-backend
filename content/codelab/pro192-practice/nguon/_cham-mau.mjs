const norm = (s) => {
  let lines = String(s).replace(/\r\n?/g, '\n').split('\n').map((l) => l.replace(/[ \t]+$/, ''));
  if (DE.loose) lines = lines.map((l) => l.replace(/[ \t]+/g, ' ').trim());
  while (lines.length && lines[lines.length - 1] === '') lines.pop();
  return lines;
};
const show = (s) => JSON.stringify(s ?? '').slice(1, -1);
function runCase(c) {
  const dir = fs.mkdtempSync(path.join(work, 'case-'));
  for (const [f, text] of Object.entries(c.files || {})) {
    fs.mkdirSync(path.dirname(path.join(dir, f)), { recursive: true });
    fs.writeFileSync(path.join(dir, f), text);
  }
  const sessions = c.sessions || [c.input ?? ''];
  let out = '', err = '', crash = null;
  sessions.forEach((input, i) => {
    if (crash) return;
    if (i > 0) out += `===== RESTART: session ${i + 1} (same folder, files kept) =====\n`;
    const r = spawnSync(java.cmd, ['-Dfile.encoding=UTF-8', '-Dstdout.encoding=UTF-8', '-Dsun.stdout.encoding=UTF-8', '-Duser.language=en', '-Duser.country=US',
      '-cp', build, ...(c.argsJava || []), DE.main, ...(c.args || [])],
    { cwd: dir, input, encoding: 'utf8', timeout: DE.timeoutMs, maxBuffer: 1 << 24 });
    out += r.stdout || '';
    err += r.stderr || '';
    if (r.error && r.error.code === 'ETIMEDOUT') crash = `TIMEOUT after ${DE.timeoutMs} ms — an endless loop? (e.g. the menu never reads the exit choice) · quá giờ — vòng lặp vô tận?`;
    else if (r.status !== 0 || /Exception in thread|^Exception|Error: /m.test(r.stderr || '')) {
      crash = `CRASHED (exit ${r.status ?? r.signal}) · chương trình SẬP:\n${String(r.stderr || '').split(/\r?\n/).filter(Boolean).slice(0, 6).map((l) => '      ' + l).join('\n')}`;
    }
  });
  return { out, err, crash };
}

