-- 001_core.sql — bảng lõi của LabFlow (Chương 12). Mỗi luật nghiệp vụ làm được bằng ràng buộc thì để CSDL giữ.
-- id giữ ĐÚNG hình dạng của hợp đồng ('lab_1', 'bk_42'): client không biết, cũng không cần biết, ta đã đổi chỗ lưu.
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- để EXCLUDE trộn được "=" (lab_id) với "&&" (khoảng thời gian)
CREATE EXTENSION IF NOT EXISTS unaccent;     -- tìm "phong" ra "Phòng" (bộ lọc q của bài 3.3)

CREATE TABLE users (
  id            text PRIMARY KEY,
  name          text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  role          text NOT NULL CHECK (role IN ('STUDENT', 'LAB_MANAGER')),
  email         text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  failed_logins int  NOT NULL DEFAULT 0,
  staff_note    text,
  created_at    timestamptz(3) NOT NULL DEFAULT now()
);

CREATE TABLE api_keys (                       -- bài 6.1: chỉ lưu sha256 của khoá
  hash       text PRIMARY KEY,
  user_id    text NOT NULL REFERENCES users ON DELETE CASCADE,
  prefix     text NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT now()
);
CREATE INDEX api_keys_user ON api_keys (user_id);

CREATE TABLE labs (
  id         text PRIMARY KEY,
  code       text NOT NULL UNIQUE,
  name       text NOT NULL,
  building   text NOT NULL,
  capacity   int  NOT NULL CHECK (capacity > 0),
  retired_at timestamptz(3)
);

CREATE SEQUENCE devices_seq;
CREATE TABLE devices (
  id         text PRIMARY KEY DEFAULT 'dev_' || nextval('devices_seq'),
  lab_id     text NOT NULL REFERENCES labs,
  name       text NOT NULL,
  type       text NOT NULL CHECK (type IN ('ROUTER', 'SWITCH', 'BOARD', 'PC', 'OTHER')),
  serial_no  text NOT NULL UNIQUE,            -- bài 2.3: trùng serial ⇒ 409 DUPLICATE_SERIAL
  status     text NOT NULL CHECK (status IN ('AVAILABLE', 'IN_USE', 'MAINTENANCE')),
  note       text,
  manual_url text,
  version    int  NOT NULL DEFAULT 1          -- bài 5.4: ETag "dev_1-v3"
);
CREATE INDEX devices_lab ON devices (lab_id);

-- timestamptz(3): làm tròn tới MILI giây — đúng độ mịn của JSON/JavaScript. Cột µs mặc định + con trỏ ISO (ms) ⇒ trang sót dòng (bài 12.1).
CREATE TABLE bookings (
  seq           bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id            text GENERATED ALWAYS AS ('bk_' || seq) STORED PRIMARY KEY,
  lab_id        text NOT NULL REFERENCES labs,
  user_id       text NOT NULL REFERENCES users,
  start_at      timestamptz(3) NOT NULL,
  end_at        timestamptz(3) NOT NULL,
  purpose       text,
  status        text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CHECKED_IN', 'CANCELLED')),
  created_at    timestamptz(3) NOT NULL DEFAULT now(),
  cancelled_at  timestamptz(3),
  checked_in_at timestamptz(3),
  version       int NOT NULL DEFAULT 1,       -- bài 10.6: sự kiện mang version để bên nhận xếp đúng thứ tự
  CONSTRAINT bookings_time_order CHECK (end_at > start_at),
  -- bài 11.6: một phòng không có hai lượt CÒN HIỆU LỰC chồng giờ — 50 người cùng bấm thì đúng 1 người được
  CONSTRAINT bookings_no_overlap EXCLUDE USING gist (lab_id WITH =, tstzrange(start_at, end_at) WITH &&)
    WHERE (status <> 'CANCELLED')
);
-- Index theo TRUY VẤN thật (bài 3.2): "lượt của tôi, mới nhất trước" và "mọi lượt, mới nhất trước" (quản lý)
CREATE INDEX bookings_user_newest ON bookings (user_id, created_at DESC, seq DESC);
CREATE INDEX bookings_newest ON bookings (created_at DESC, seq DESC);

CREATE SEQUENCE waitlist_seq;
CREATE TABLE waitlist (                       -- Lab 7
  id         text PRIMARY KEY DEFAULT 'wl_' || nextval('waitlist_seq'),
  lab_id     text NOT NULL REFERENCES labs,
  user_id    text NOT NULL REFERENCES users,
  start_at   timestamptz(3) NOT NULL,
  end_at     timestamptz(3) NOT NULL,
  purpose    text,
  status     text NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING', 'CANCELLED')),
  created_at timestamptz(3) NOT NULL DEFAULT now()
);
CREATE INDEX waitlist_lab ON waitlist (lab_id) WHERE status = 'WAITING';
