-- 004_issues.sql — Lab 12 (LỜI GIẢI): báo hỏng thiết bị chuyển từ RAM vào PostgreSQL.
CREATE TABLE issues (
  seq           bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id            text GENERATED ALWAYS AS ('iss_' || seq) STORED PRIMARY KEY,
  device_id     text NOT NULL REFERENCES devices ON DELETE CASCADE,
  reported_by   text NOT NULL REFERENCES users,
  title         text NOT NULL,
  title_key     text NOT NULL,                -- fold(title) do app tính (unaccent() không IMMUTABLE nên không index thẳng được)
  severity      text NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
  severity_rank smallint GENERATED ALWAYS AS (CASE severity WHEN 'LOW' THEN 1 WHEN 'MEDIUM' THEN 2 ELSE 3 END) STORED,
  description   text,
  status        text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED')),
  created_at    timestamptz(3) NOT NULL DEFAULT now(),
  resolved_at   timestamptz(3),
  resolution    text,
  version       int NOT NULL DEFAULT 1
);
-- Luật Lab 1 "không hai báo hỏng ĐANG MỞ cùng tiêu đề trên một thiết bị" — giữ bằng index duy nhất CÓ ĐIỀU KIỆN
CREATE UNIQUE INDEX issues_open_title ON issues (device_id, title_key) WHERE status = 'OPEN';
CREATE INDEX issues_newest ON issues (created_at DESC, seq DESC);
CREATE INDEX issues_device ON issues (device_id);
