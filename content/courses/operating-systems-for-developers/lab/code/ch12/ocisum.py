# ocisum.py config.json — tóm tắt một OCI runtime spec (bài 12.6): những trường quyết định "container" là gì.
import json, sys
c = json.load(open(sys.argv[1]))
p, lx = c["process"], c.get("linux", {})
print("ociVersion   ", c["ociVersion"])
print("process.args ", p["args"], " user", p["user"]["uid"], " cwd", p["cwd"])
print("root         ", c["root"]["path"], " readonly=%s" % c["root"].get("readonly", False))
print("hostname     ", c.get("hostname"))
print("namespaces   ", " ".join(n["type"] for n in lx.get("namespaces", [])))
print("mounts       ", " ".join(m["destination"] for m in c.get("mounts", [])))
caps = p.get("capabilities", {}).get("bounding", [])
print("capabilities ", len(caps), "in bounding set")
r = lx.get("resources", {})
print("resources    ", "memory=%s" % r.get("memory", {}).get("limit"), "cpu=%s/%s" % (r.get("cpu", {}).get("quota"), r.get("cpu", {}).get("period")), "pids=%s" % r.get("pids", {}).get("limit"))
print("cgroupsPath  ", lx.get("cgroupsPath"))
s = lx.get("seccomp")
print("seccomp      ", "none" if not s else "default %s, %d rules naming %d syscalls" % (s["defaultAction"], len(s.get("syscalls", [])), sum(len(r.get("names", [])) for r in s.get("syscalls", []))))
print("masked/ro    ", len(lx.get("maskedPaths", [])), "masked paths,", len(lx.get("readonlyPaths", [])), "read-only paths")
print("apparmor     ", p.get("apparmorProfile", "-"), " noNewPrivileges=%s" % p.get("noNewPrivileges", False))
