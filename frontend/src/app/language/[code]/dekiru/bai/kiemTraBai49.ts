/** Câu ngữ pháp có số ポイント (để dựng bảng "sai câu nào ôn ポイント nào"). */
type NP = { pt: number; q: QI };
const G = (pt: number, q: string, ok: string, bad: string, why: string): NP => ({ pt, q: Q(q, ok, bad, `**ポイント ${pt}** — ${why}`) });

type KT = {
  n: number;
  /** Tên bài ngắn (chủ đề). */
  ten: string;
  /** Khoảng ポイント của bài. */
  pts: string;
  doan: [Doan, Doan];
  qa: QA[];
  tu: QI[];
  han: QI[];
  ngu: NP[];
  doc: { tieuDe: string; paras: string[]; cau: QI[] };
  /** Ghi chú riêng (vd. Bài 8–9 ngoài phạm vi đề JPD123). */
  ghi?: string;
};

function kiemTra(k: KT): Lesson[] {
  const n = k.n;
  const noi: Lesson = {
    id: `b${n}-kiem-tra-noi`,
    kind: 'review',
    title: `Kiểm tra Bài ${n} — đúng form thi · Phần NÓI (2 đoạn Reading + 6 câu Q&A)`,
    goal: `Đọc trôi chảy 2 đoạn kiểu đề A chỉ dùng từ và ngữ pháp đến Bài ${n}, và trả lời trọn câu 6 câu hỏi Q&A của Bài ${n} như trong phòng thi.`,
    minutes: 25,
    blocks: [
      RECAP(`Kiểm tra nói Bài ${n} — ${k.ten}`, [
        'Làm như thi thật: **20 giây** nhìn tờ đề → đọc to MỘT lượt → mở máy chấm phát âm từng câu.',
        'Chữ **in đậm** = chữ Hán của lớp bị gạch chân trên đề thật (không furigana).',
        'Q&A: nghe câu hỏi ở khối 🎤, ghi âm câu trả lời **trọn câu + 1 ý thêm**, rồi so với 2 cách trả lời mẫu.',
        ...(k.ghi ? [k.ghi] : []),
      ]),
      ...khoiDoan(k.doan[0], `b${n}-kt-r1`, `Reading 1 — ${k.doan[0].ten}${k.doan[0].mo ? ` (mở rộng ${k.doan[0].mo})` : ''}`),
      ...khoiDoan(k.doan[1], `b${n}-kt-r2`, `Reading 2 — ${k.doan[1].ten}${k.doan[1].mo ? ` (mở rộng ${k.doan[1].mo})` : ''}`),
      ...khoiNhom({ ma: `Q&A Bài ${n}`, ten: k.ten, slug: 'qa', ds: k.qa }, `b${n}-kt`),
    ],
  };

  const bang: string[][] = [];
  const nhomPt = new Map<number, number[]>();
  k.ngu.forEach((x, i) => { const so = 21 + i; nhomPt.set(x.pt, [...(nhomPt.get(x.pt) ?? []), so]); });
  bang.push(['1–10 (từ vựng)', `\`b${n}-tu-vung\` — Từ vựng Bài ${n} (ôn thêm bằng 🃏 Ôn tập bằng thẻ, chọn Bài ${n})`]);
  bang.push(['11–20 (chữ Hán)', `\`b${n}-han-lop\` — Chữ Hán của lớp Bài ${n}${n >= 8 ? ' (danh sách dự kiến)' : ''} + \`b${n}-kanji\``]);
  for (const [pt, cs] of [...nhomPt.entries()].sort((a, b) => a[0] - b[0])) bang.push([cs.map((c) => `Câu ${c}`).join(', '), `**ポイント ${pt}** trong \`b${n}-ngu-phap\``]);
  bang.push(['36–40 (đọc hiểu)', `Bài đọc của \`b${n}-ngu-phap\` / luyện thêm Bài ${n}; đọc lại cả đoạn, gạch từ nối (そして・が・それから…)`]);

  const viet: Lesson = {
    id: `b${n}-kiem-tra-viet`,
    kind: 'review',
    title: `Kiểm tra Bài ${n} — đúng form thi · Phần VIẾT 40 câu (từ vựng · chữ Hán · ngữ pháp · đọc) — thang 10`,
    goal: `Làm bài kiểm tra 40 câu của Bài ${n} (ポイント ${k.pts}) trong 30 phút, tự chấm thang 10 và biết sai câu nào thì ôn ポイント nào.`,
    minutes: 30,
    blocks: [
      RECAP(`Kiểm tra viết Bài ${n} — 40 câu · 30 phút · 0,25 điểm/câu`, [
        'Khuôn **bài kiểm tra trên lớp** (như đề ôn giữa kỳ Bài 4–5 của cô): từ vựng · chữ Hán (đáp án nhiễu là chữ na ná) · ngữ pháp, thêm phần đọc hiểu như đề cuối kỳ.',
        'Phần chữ Hán **không có furigana**. Làm hết một phần rồi mới bấm xem đáp án.',
        'Mục tiêu **≥ 36/40 câu (9 điểm)**. Câu sai: xem bảng cuối bài để biết ôn ポイント nào.',
        ...(k.ghi ? [k.ghi] : []),
      ]),
      TABLE(['Phần', 'Câu', 'Số câu', 'Điểm'], [
        ['I. Từ vựng', '1–10', '10', '2,5'],
        ['II. Chữ Hán', '11–20', '10', '2,5'],
        ['III. Ngữ pháp', '21–35', '15', '3,75'],
        ['IV. Đọc hiểu', '36–40', '5', '1,25'],
        ['Tổng', '', '**40**', '**10**'],
      ]),
      H('I. Từ vựng (câu 1–10)'),
      MC(`b${n}-kt-tu`, `I. Từ vựng Bài ${n} — câu 1–10: chọn từ điền vào（　）`, k.tu),
      H('II. Chữ Hán (câu 11–20)'),
      MC(`b${n}-kt-han`, `II. Chữ Hán — câu 11–20: chữ trong 【 】 đọc thế nào / viết bằng chữ nào`, k.han),
      H('III. Ngữ pháp (câu 21–35)'),
      MC(`b${n}-kt-ngu`, `III. Ngữ pháp Bài ${n} — câu 21–35 (mỗi câu ghi ポイント cần ôn)`, k.ngu.map((x) => x.q)),
      H('IV. Đọc hiểu (câu 36–40)'),
      { t: 'passage', title: k.doc.tieuDe, intro: 'Đọc đoạn văn rồi trả lời. Chỗ trống（①）（②）（③）chọn từ thích hợp; câu 39–40 hỏi nội dung.', paras: k.doc.paras.map((text) => ({ text })) },
      MC(`b${n}-kt-doc`, 'IV. Đọc hiểu — câu 36–40', k.doc.cau),
      H('Thang điểm & sai câu nào ôn ポイント nào'),
      TABLE(
        ['Số câu đúng (/40)', 'Điểm (/10)', 'Làm gì tiếp'],
        [
          ['38 – 40', '9,5 – 10', '✅ Vững Bài ' + n + ' — sang bài tiếp / làm đề thi thử'],
          ['36 – 37', '9 – 9,25', '✅ Đạt mục tiêu — ôn riêng câu sai'],
          ['32 – 35', '8 – 8,75', 'Ôn ポイント của câu sai rồi làm lại phần đó'],
          ['24 – 31', '6 – 7,75', 'Đọc lại bài ngữ pháp + từ vựng Bài ' + n + ', làm lại sau 1 ngày'],
          ['< 24', '< 6', '⚠️ Học lại Bài ' + n + ' từ đầu (hội thoại → từ vựng → ngữ pháp)'],
        ],
        'Điểm = số câu đúng × 0,25',
      ),
      TABLE(['Câu sai', 'Ôn ở đâu'], bang),
    ],
  };
  return [noi, viet];
}

