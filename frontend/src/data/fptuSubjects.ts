/** Ô giữ chỗ trong khung (SE_COM*1, PHE_COM*2, TMI_ELE…) chứ không phải môn
 *  thật: FLM đánh dấu chỗ sinh viên sẽ chọn môn theo combo hoặc tự chọn. */
export const isPlaceholderCode = (code: string): boolean =>
  /[*]/.test(code) || /_(ELE|COM\d?)/.test(code) || /^(PEN|TMI|PHE\d?|OSG20x)$/.test(code) || /^RA-COM\d$/.test(code);

export const subjectName = (code: string): string | undefined => SUBJECT_NAMES[code];

/**
 * Nhãn tiếng Việt cho ô giữ chỗ. Lấy đúng theo cột Subject Name của FLM khi
 * trường có ghi (PHE_COM*1 = "Physical Education 1", XX_COM*N = "Học phần N
 * của combo", XX_GRA_ELE = "Học phần lựa chọn Đồ án tốt nghiệp"); mã nào
 * trường không chú thích thì để nhãn trung tính, KHÔNG đoán tên môn.
 */
export function placeholderLabel(code: string): string {
  if (/^PHE/.test(code)) return 'Giáo dục thể chất';
  if (/_GRA_ELE/.test(code)) return 'Đồ án tốt nghiệp (chọn học phần)';
  if (/_COM\*?\d/.test(code) || /^RA-COM\d$/.test(code)) return 'Học phần của combo';
  if (/_ELE/.test(code)) return 'Học phần tự chọn';
  if (code === 'OSG20x') return 'Hệ điều hành (trường xếp phiên bản)';
  if (code === 'PEN' || code === 'TMI' || code === 'OTP101') return 'Học phần đầu khoá do trường xếp';
  return 'Học phần trường xếp';
}
