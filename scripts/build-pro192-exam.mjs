/**
 * build-pro192-exam.mjs — generic builder for any PRO192 FE deck: merges the
 * raw solved-question batch JSON files, syntax-highlights embedded Java code
 * with highlight.js, and emits a content/exams/*.mjs spec ready for
 * academy-seed-exam.mjs. Generalized from build-pro192-fe1.mjs so it works
 * for every deck (Đề 2..10) without copy-pasting a new script each time.
 *
 *   node scripts/build-pro192-exam.mjs \
 *     --raw-glob "/path/to/scratch/pro192-fe2-raw*.json" \
 *     --images /path/to/scratch/pro192-fe2-image-urls.json \
 *     --code DE2-SP26-B5FE \
 *     --title "PRO192 — Final Exam Đề 2 (SP26 B5FE)|||PRO192 — Đề thi cuối kỳ số 2 (SP26 B5FE)" \
 *     --out content/exams/PRO192-FE2.mjs \
 *     --count 50
 */
import fs from 'node:fs';
import path from 'node:path';
import { globSync } from 'node:fs';
import hljs from 'highlight.js';

const args = process.argv.slice(2);
const val = (f) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : undefined; };

const RAW_GLOB = val('--raw-glob');
const IMAGES_PATH = val('--images');
const CODE = val('--code');
const TITLE = val('--title');
const OUT = val('--out');
const COUNT = parseInt(val('--count') || '50', 10);

if (!RAW_GLOB || !CODE || !TITLE || !OUT) {
  console.error('cần --raw-glob --code --title --out (và tuỳ chọn --images --count)');
  process.exit(1);
}

function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function codeBlockHtml(code) {
  const highlighted = hljs.highlight(code, { language: 'java' }).value;
  return `<pre><code class="language-java">${highlighted}</code></pre>`;
}

function buildPromptHtml(q, lang) {
  const text = lang === 'en' ? q.questionTextEn : q.questionTextVi;
  let html = `<p>${esc(text).replace(/\n/g, '<br/>')}</p>`;
  if (q.hasCode && q.codeJava) {
    html += codeBlockHtml(q.codeJava);
  }
  return html;
}

const files = globSync(RAW_GLOB).sort();
if (!files.length) {
  console.error(`✗ no files matched glob: ${RAW_GLOB}`);
  process.exit(1);
}
console.log(`✓ found ${files.length} raw batch file(s)`);

let all = [];
for (const f of files) {
  const arr = JSON.parse(fs.readFileSync(f, 'utf8'));
  all = all.concat(arr);
}
all.sort((a, b) => a.n - b.n);

if (all.length !== COUNT) {
  console.error(`✗ Expected ${COUNT} questions, got ${all.length}`);
  process.exit(1);
}
const seen = new Set();
for (const q of all) {
  if (seen.has(q.n)) { console.error(`✗ duplicate n=${q.n}`); process.exit(1); }
  seen.add(q.n);
}
for (let i = 1; i <= COUNT; i++) {
  if (!seen.has(i)) { console.error(`✗ missing n=${i}`); process.exit(1); }
}
console.log(`✓ ${COUNT}/${COUNT} questions present, n=1..${COUNT}`);

let imageUrls = {};
if (IMAGES_PATH && fs.existsSync(IMAGES_PATH)) {
  imageUrls = JSON.parse(fs.readFileSync(IMAGES_PATH, 'utf8'));
  console.log(`✓ loaded ${Object.keys(imageUrls).length} image URLs`);
} else {
  console.warn(`⚠ no image URL map — questions will have NO imageUrl`);
}

let unconfident = [];
const questions = all.map((q) => {
  if (q.confident === false) unconfident.push(q.n);

  const promptEn = buildPromptHtml(q, 'en');
  const promptVi = buildPromptHtml(q, 'vi');
  const prompt = `${promptEn}|||${promptVi}`;

  const options = q.options.map((o) => ({ text: `${o.en}|||${o.vi}` }));

  const correctIndexes = Array.isArray(q.correctIndexes) ? q.correctIndexes : [q.correctIndex];

  let explanation = `${q.explanationEn}|||${q.explanationVi}`;
  if (q.confident === false && q.confidenceNote) {
    explanation += ` [[UNCERTAIN — CẦN RÀ LẠI: ${q.confidenceNote}]]`;
  }

  const imageUrl = imageUrls[String(q.n)] || undefined;

  return {
    kind: 'MCQ',
    points: +(10 / COUNT).toFixed(2),
    prompt,
    ...(imageUrl ? { imageUrl } : {}),
    options,
    correctIndexes,
    explanation,
  };
});

const spec = {
  course: { courseCode: 'PRO192' },
  exams: [
    {
      kind: 'FE',
      code: CODE,
      title: TITLE,
      description: `Đề trắc nghiệm FE thật của PRO192 (${COUNT} câu), có lời giải chi tiết song ngữ tự soạn.|||Đề trắc nghiệm FE thật của PRO192 (${COUNT} câu), có lời giải chi tiết song ngữ tự soạn.`,
      durationMinutes: 60,
      totalPoints: 10,
      passMark: 5,
      shuffleQuestions: true,
      shuffleOptions: true,
      source: 'REAL',
      isPublished: true,
      questions,
    },
  ],
};

const out = `// AUTO-GENERATED by scripts/build-pro192-exam.mjs — do not hand-edit, re-run the builder instead.
export default ${JSON.stringify(spec, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`✓ wrote ${OUT} (${questions.length} questions)`);
if (unconfident.length) {
  console.log(`⚠ ${unconfident.length} question(s) marked UNCERTAIN: n=${unconfident.join(', ')}`);
}
if (!Object.keys(imageUrls).length) {
  console.log(`⚠ NO images attached — run the R2 upload script first, then re-run this builder.`);
}
