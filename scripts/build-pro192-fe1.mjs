/**
 * build-pro192-fe1.mjs — merge the 5 raw solved-question batches for
 * PRO192 Đề 1 FE, syntax-highlight embedded Java code with highlight.js,
 * and emit content/exams/PRO192-FE1.mjs ready for academy-seed-exam.mjs.
 *
 *   node scripts/build-pro192-fe1.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import hljs from 'highlight.js';

const SCRATCH = '/private/tmp/claude-501/-Users-admin-Downloads-api-backend/99b7dcaf-280f-4477-a6ab-efc246cea9e2/scratchpad';
const FILES = [
  'pro192-fe1-raw.json',
  'pro192-fe1-raw-11-20.json',
  'pro192-fe1-raw-21-30.json',
  'pro192-fe1-raw-31-40.json',
  'pro192-fe1-raw-41-50.json',
];

const IMAGE_URL_MAP_PATH = path.join(SCRATCH, 'pro192-fe1-image-urls.json');

function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function codeBlockHtml(code) {
  const highlighted = hljs.highlight(code, { language: 'java' }).value;
  return `<pre><code class="language-java">${highlighted}</code></pre>`;
}

function buildPromptHtml(q, lang) {
  const text = lang === 'en' ? q.questionTextEn : q.questionTextVi;
  let html = `<p>${esc(text).replace(/\n/g, '<br/>')}</p>`;
  if (q.hasCode && q.codeJava) {
    html += codeBlockHtml(q.codeJava);
  }
  return html;
}

let all = [];
for (const f of FILES) {
  const raw = fs.readFileSync(path.join(SCRATCH, f), 'utf8');
  const arr = JSON.parse(raw);
  all = all.concat(arr);
}

all.sort((a, b) => a.n - b.n);

if (all.length !== 50) {
  console.error(`✗ Expected 50 questions, got ${all.length}`);
  process.exit(1);
}
const seen = new Set();
for (const q of all) {
  if (seen.has(q.n)) { console.error(`✗ duplicate n=${q.n}`); process.exit(1); }
  seen.add(q.n);
}
for (let i = 1; i <= 50; i++) {
  if (!seen.has(i)) { console.error(`✗ missing n=${i}`); process.exit(1); }
}
console.log(`✓ 50/50 questions present, n=1..50`);

let imageUrls = {};
if (fs.existsSync(IMAGE_URL_MAP_PATH)) {
  imageUrls = JSON.parse(fs.readFileSync(IMAGE_URL_MAP_PATH, 'utf8'));
  console.log(`✓ loaded ${Object.keys(imageUrls).length} image URLs from ${IMAGE_URL_MAP_PATH}`);
} else {
  console.warn(`⚠ no image URL map found at ${IMAGE_URL_MAP_PATH} — questions will have NO imageUrl (upload to R2 first, then re-run)`);
}

let unconfident = [];
const questions = all.map((q) => {
  if (q.confident === false) unconfident.push(q.n);

  const promptEn = buildPromptHtml(q, 'en');
  const promptVi = buildPromptHtml(q, 'vi');
  const prompt = `${promptEn}|||${promptVi}`;

  const options = q.options.map((o) => ({ text: `${o.en}|||${o.vi}` }));

  const correctIndexes = Array.isArray(q.correctIndexes) ? q.correctIndexes : [q.correctIndex];

  let explanation = `${q.explanationEn}|||${q.explanationVi}`;
  if (q.confident === false && q.confidenceNote) {
    explanation += ` [[UNCERTAIN — CẦN RÀ LẠI: ${q.confidenceNote}]]`;
  }

  const imageUrl = imageUrls[String(q.n)] || undefined;

  return {
    kind: 'MCQ',
    points: 0.2,
    prompt,
    ...(imageUrl ? { imageUrl } : {}),
    options,
    correctIndexes,
    explanation,
  };
});

const spec = {
  course: { courseCode: 'PRO192' },
  exams: [
    {
      kind: 'FE',
      code: 'DE1-SU26',
      title: 'PRO192 — Final Exam Đề 1 (SU26)|||PRO192 — Đề thi cuối kỳ số 1 (SU26)',
      description: 'Đề trắc nghiệm FE thật của PRO192 (kỳ SU26, 50 câu), có lời giải chi tiết song ngữ tự soạn.|||Đề trắc nghiệm FE thật của PRO192 (kỳ SU26, 50 câu), có lời giải chi tiết song ngữ tự soạn.',
      durationMinutes: 60,
      totalPoints: 10,
      passMark: 5,
      shuffleQuestions: true,
      shuffleOptions: true,
      source: 'REAL',
      isPublished: true,
      questions,
    },
  ],
};

const out = `// AUTO-GENERATED by scripts/build-pro192-fe1.mjs — do not hand-edit, re-run the builder instead.
export default ${JSON.stringify(spec, null, 2)};
`;

fs.writeFileSync('content/exams/PRO192-FE1.mjs', out);
console.log(`✓ wrote content/exams/PRO192-FE1.mjs (${questions.length} questions)`);
if (unconfident.length) {
  console.log(`⚠ ${unconfident.length} question(s) marked UNCERTAIN, flagged in explanation: n=${unconfident.join(', ')}`);
}
if (!Object.keys(imageUrls).length) {
  console.log(`⚠ NO images attached yet — run the R2 upload script first, then re-run this builder.`);
}
